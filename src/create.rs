//
// # 作用与使用位置
//
// 以后单独冻结的跨进程协调式新建接口必须在一个受控流程中建立目标、稳定
// 文件身份、协调协议、公开授权和首个文件资源。成功时使用本类型同时交付
// 后两项，避免调用方收到授权后再执行一次可能失败且浪费底层打开的操作。
//
// `A` 对应 [`crate::FileNamespace::CrossProcessAuthority`]，`F` 对应
// [`crate::FileNamespace::File`]。类型定义不重复这些关联类型约束，使本
// helper 也能服务第三方 adapter 的具体类型；真正的 namespace 方法签名
// 负责把两者约束到同一个实现。
//
// 本类型只是成功结果载体，不实现 [`crate::FileIo`]，也不通过 `Deref`、
// `AsRef<F>` 或隐式转换伪装成普通文件。调用方必须显式访问或拆解文件字段，
// 从而持续看见与它配对的跨进程授权。
//
// # 所有权、释放顺序与基本能力
//
// 两个字段均为拥有型且对库外私有。内部声明顺序刻意先放置 `file`，再放置
