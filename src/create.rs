// 单个 namespace 目标创建失败时的副作用证据。
//
// [`CreateTargetEvidence`] 只回答“本次创建操作是否建立过目标”这一问题。
// 它不把一次易受并发和远端完成不确定性影响的创建失败，误报成目标当前
// 存在或不存在的实时断言。后续创建失败载体会拥有一个本类型值，使调用方
// 能把诊断原因与本次操作的可证明副作用一起处理。

