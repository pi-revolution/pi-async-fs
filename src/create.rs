// 创建操作失败时，本次操作对目标条目的可证明影响。
//
// # 作用与使用位置
//
// 本类型用于一次操作只创建一个最终 namespace 目标的普通错误结果，包括
// 原子排他创建普通文件、跨进程协调式创建普通文件和单层目录创建。创建成功
// 时直接返回该接口自己的成功值，不附带本类型；查询目标是否存在、读取元
// 信息、覆盖已有目标和创建临时文件也不使用本类型。
//
// 递归建目录可能创建多个中间目标，不能用一个三态值完整表达已经发生的
// 副作用，因此明确不使用本类型。复制、改名、替换、截断和覆盖同样具有
// 不同的提交点或恢复资产，必须使用各自单独冻结的结果合同。
//
// 它描述的是“本次操作是否创建过目标”，不是读取错误结果时 namespace 的
// 实时状态。其它线程、进程或远端参与者可能在创建操作之后立即修改、改名
// 或删除目标；因此任何变体都不能代替新的存在性查询、稳定身份核验或协调
// 租约。
//
// # 失败副作用与重试边界
//
// 本库不会在创建成功而后续稳定身份查询、协调登记或资源交付失败时，自动
// 删除已经创建的目标。自动补偿删除会与已经观察或使用该文件、目录或远端
// 等价目标的其它参与者竞争，并可能删除不再属于本次操作的 namespace 条目。
//
// 本类型刻意不提供 `is_retry_safe`。即使证据是
// [`Self::NotCreatedByOperation`]，调用方仍须结合错误种类、外部并发和所需
// 幂等语义判断能否重试；[`Self::CreatedByOperation`] 与 [`Self::Unknown`]
// 更不能被解释为可以再次执行原创建方法。
//
// 丢弃尚未完成的创建 Future 没有返回本证据的通道。若原生创建已经提交，
// 后台完成所有者仍须完成资源清理，但新建目标可能保留。创建方法必须
// 在自己的取消合同中再次公开这一边界。
//
// # 基本能力与演进
//
// 本类型刻意不实现 `Clone`、`Copy` 或 `Default`。它实现调试、显示、判等、
// 全序和哈希，以支持诊断、确定性索引和问题归档；排序只比较证据标签，不
// 表示可靠程度、时间先后或重试优先级。`Send` 与 `Sync` 由无字段枚举自动
// 获得，不使用手写 `unsafe impl`。
//
// 本类型不承诺稳定 ABI、整数判别值、序列化格式或可反向解析的文本协议。
// `#[non_exhaustive]` 要求库外调用方保留保守分支，以便以后增加更精确而不
// 削弱现有语义的可移植证据。
#[non_exhaustive]
/// 创建操作失败时，对目标条目是否由本次操作创建的可证明事实。
///
/// 证据只描述本次调用的历史，不是目标当前位置的实时查询，也不单独表示
/// 可以安全重试。它不提供持久化保证。
pub enum CreateTargetEvidence {
    // 能证明本次操作没有创建目标条目。
    //
    // 本变体不证明目标当前不存在。常见情况包括目标原本已经存在、创建前
    // 参数或角色校验失败，以及在原生创建提交前被协调状态明确拒绝。
    /// 能证明本次操作没有创建目标条目。
    ///
    /// 这不证明目标当前位置为空；其它参与者可能已经创建对象。
    NotCreatedByOperation,

    // 能证明本次操作已经创建过目标条目。
    //
    // 后续错误可能来自稳定身份查询、进程内协调登记、跨进程协议步骤或已
    // 打开资源的交付阶段。本变体不证明目标仍位于原 locator，不证明它仍是
    // 同一个稳定对象，也不证明空内容、目录项或元信息已经持久化。
    /// 能证明本次操作已经创建过目标条目。
    ///
    /// 这不证明目标当前仍存在、仍位于原位置或已经持久化。
    CreatedByOperation,

    // 无法证明本次操作是否创建过目标条目。
    //
    // 常见来源包括远端提交响应丢失、取消与后台完成竞态，以及无法给出
    // 可移植提交证据的第三方 adapter。调用方必须按可能已经创建处理。
    /// 无法证明本次操作是否创建过目标条目。
    ///
    /// 调用方必须按“可能已经创建”处理并重新查询。
    Unknown,
}

