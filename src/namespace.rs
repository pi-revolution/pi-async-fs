    //
    // 取消没有 [`RemoveFailure`] 返回通道，因此目标可能仍存在、已经移除或
    // 结果未知。严格空目录删除不是状态或响应幂等操作：一次成功后重试通常
    // 返回不存在，未知结果下盲目重试还可能删除后来在相同位置创建的新空
    // 目录。调用方必须重新查询并在需要时核验对象身份。
    //
    // 成功只表示名称绑定已移除或 backend 已不可撤销地接受该动作，不隐式
    // 刷新物理父目录、卷或远端目录索引，也不保证掉电、操作系统崩溃、失信
    // 硬件缓存或硬件损坏后的持久性。其它已打开目录句柄或平台内部引用可以
