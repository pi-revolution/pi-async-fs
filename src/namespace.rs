    //
    // # 副作用与性能
    //
    // 本方法会修改 namespace，并可能打开父目录和目标目录探测句柄、查询
    // 稳定身份、更新进程内协调状态、执行系统调用或远端请求、分配临时状态
    // 并记录日志或指标，因此不是纯函数。它不调用用户回调，不扫描或删除
