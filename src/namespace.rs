    // 排它地移除一个已经存在的空目录。
    //
    // # 作用与接口层级
    //
    // 本方法是当前进程受管协调域中的安全默认单目录移除入口。它只移除
    // locator 对应的一个空目录名称，不递归、不删除任何子项，也不把目录
    // 转换成文件删除。目标不存在、不是目录或在底层提交点仍然非空时必须
    // 返回错误。
    //
    // 名称沿用 Rust 标准库的 `remove_dir`；“只能删除空目录”是本接口的
    // 强制语义，而不是可选模式。本 crate 不提供 `remove_dir_all` 或其它
    // 递归目录树删除接口，也不能通过布尔参数、选项或隐式回退把多目标删除
    // 混入本方法。确需清理目录树的上层调用方必须显式枚举、逐项选择操作并
    // 自行处理部分进度、并发变化和恢复策略。
    //
    // # 参数、借用与返回值
    //
    // `locator` 在返回 Future 的 `'a` 生命周期内共享借用，不被消费。成功
    // 只返回 `()`，因为目录绑定移除后没有目录句柄或 guard 可以合法交付。
    // 调用方继续拥有原 locator，但它只是位置表示；成功后同一位置可以被
    // 其它参与者用于创建另一个目录、文件或其它 backend 对象。
    //
    // Future 为 `Send + 'a`，可以在 namespace 与 locator 的借用期内跨工作
    // 线程迁移，不绑定 Tokio、async-std、smol、Monoio 或其它运行时。只有
    // 阻塞任务或取消后的完成者必须脱离调用栈时，adapter 才需要克隆拥有型
    // locator；该克隆不构成稳定目录身份证明。
    //
    // # 类型、最终符号链接与根目录
    //
    // 最终路径分量必须解析为本接口支持的真实目录。最终分量是普通符号链接、
    // 悬空符号链接、Windows 重解析点或其它非目录对象时，本方法不得跟随其
    // 目标，也不得删除链接自身；应返回准确类型或不支持错误。删除链接自身
    // 必须使用 [`Self::remove_file`] 或明确选择更弱协调语义的对应入口。
    //
    // 中间路径分量仍按 adapter 的正常解析规则处理，本方法不是路径沙箱。
    // namespace 根、文件系统挂载点、卷根、进程当前工作目录或平台保留目录
    // 可以因平台规则返回忙、权限或无效操作错误；实现不能通过切换工作目录、
    // 卸载文件系统或修改权限来强制删除。
    //
    // # 空目录条件与线性化点
    //
    // adapter 必须使用平台或 backend 提供的原生“仅删除空目录”原语作为
    // 最终提交点。不能先调用 [`Self::read_dir`] 判断为空，再调用一个不带
    // 空目录前置条件的通用删除；枚举完成与删除之间可以并发加入新子项，
    // 这种检查与使用时间差无法证明提交时仍为空。
    //
    // 本地实现应使用锚定父目录句柄的相对 `rmdir` 等价能力或平台正式空目录
    // 删除原语，以底层原语成功的瞬间作为名称绑定移除提交点。并发旁路进程
    // 在提交前建立子项时，原生删除必须失败为非空或相应竞态错误；底层删除
    // 先成功时，旁路创建必须自行处理父目录已经消失。该竞态不能产生 Rust
    // UB，也不能促使本库递归清理后来出现的子项。
    //
    // # 进程内父条目与目录内容退役许可
    //
    // 内置本地 adapter 必须按以下逻辑次序进入删除：
    //
    // 1. 解析并锚定物理父 namespace；
    // 2. 按父目录稳定身份与最终名称非阻塞取得进程内父条目拥有型许可；
    // 3. 不跟随最终分量地打开并核验目标目录，取得稳定目录身份；
    // 4. 在该目录的进程内协调核心中非阻塞登记排它内容退役许可；
    // 5. 重新核验父目录、最终条目和目标稳定身份；
    // 6. 离开同步临界区后调用原生空目录删除；
    // 7. 完成或安全失败后按相反顺序释放许可。
    //
    // 父条目许可与同一名称上的创建、删除、改名和替换互斥。内容退役许可与
    // 正在创建、删除、改名或替换该目录直接子项的当前进程操作互斥；成功
    // 登记后，新的受管子项变更必须立即失败，直到删除完成或安全撤销。任何
    // 冲突都不排队等待，不自动取消或关闭另一个调用。
    //
    // 内容退役许可只统计目录条目的 namespace 变更，不统计任何普通文件
    // 内容访问。活动或在途的 [`Self::File`]、随机读取、顺序读取、严格追加、
    // 刷新、截断、覆盖、文件 MMAP 及其透明句柄都不与本方法冲突，本方法也
    // 不查询或扫描文件稳定身份注册表。如果一个可见子文件仍在目录中，原生
    // 空目录删除自然会以非空失败；如果其名称此前已经移除，仍存活的拥有型
    // 文件句柄或映射继续管理底层对象，不再构成该目录的 namespace 子项。
    //
    // 取得的是可以跨异步阶段持有的拥有型许可，不是跨 `.await` 持有同步
    // mutex guard。同步临界区只允许稳定身份比较、状态检查、计数和许可转移；
    // 其中禁止文件 I/O、`.await`、用户回调、可能阻塞的日志和无界分配。
    // 禁止反向取锁或原地升级共享许可。多目录操作必须在以后相应 API 中按
    // 统一稳定顺序取得全部相关许可，不能与本方法形成相反锁序。
    //
    // # 目录流、递归遍历和监听
    //
    // [`Self::DirectoryStream`]、[`Self::WalkStream`] 和以后声明的文件监听
    // 资源不进入内容退役计数，也不阻止本方法。它们是非快照观察者，不是
    // namespace 锁：以目标为根的浅层流可以结束或返回明确错误；以目标为根
    // 的递归流遇到根级失败时终止；从祖先开始的递归流可以按 [`Self::walk`]
    // 合同报告局部错误并继续；监听只能报告 backend 实际提供的变化事件。
    //
    // 流项目拥有自己的 [`DirectoryEntry`] 或 [`WalkEntry`] 数据，删除目录
    // 不得使已经交付的 Rust 值失效。adapter 必须尽量用允许 namespace 删除
    // 的共享模式打开目录枚举和监听资源；平台仍因活动原生句柄拒绝删除时，
    // 本方法返回准确占用或权限错误，不能强制关闭调用方流，也不能把失败改写
    // 成成功。
    //
    // 该选择不提供一致性快照。需要“遍历期间目录树不变”的调用方必须在更
    // 高层建立自己的事务、版本或全局协调，不能依赖一个长期目录流隐式冻结
    // namespace。
    //
    // # 进程、跨进程和远端边界
    //
    // 本方法的父条目和内容退役许可只协调当前进程中共享本库注册状态的
    // adapter。它不创建跨进程 sidecar、协议记录或 `fs4` 锁，不能阻止另一
    // 进程、另一份未共享静态状态的库副本或库外原生调用并发修改目录。
    // 底层原生空目录条件仍保证这些竞态不会被本库误实现成递归删除。
    //
    // 远端 adapter 只有在 backend 具有明确的目录对象或容器语义，并能保证
    // 删除提交时目录为空时才能实现本方法。纯对象前缀、最终一致枚举后进行
    // 无条件标记删除，或无法区分空目录与字符串前缀的后端必须返回
    // `Unsupported`；不能用一次列表查询模拟原子空目录前置条件。
    //
    // # 错误与移除提交证据
    //
    // 失败通过 [`RemoveFailure`] 返回。locator 无效、目标不存在、对象不是
    // 目录、目录非空、根或挂载点不可删除、权限不足、只读文件系统、父条目
    // 或内容退役冲突、身份变化、backend 不支持，以及其它提交前失败使用
    // [`crate::RemoveTargetEvidence::NotRemovedByOperation`]。
    //
    // 原生空目录删除已经明确成功，随后发生协调收尾或结果交付失败时使用
    // [`crate::RemoveTargetEvidence::RemovedByOperation`]。远端提交已发送但
    // 确实无法证明结果时使用 [`crate::RemoveTargetEvidence::Unknown`]。
    // 任一证据都只描述本次单目录操作的 namespace 绑定提交事实，不表示同一
    // locator 当前仍为空，也不证明底层目录对象已经物理回收。
    //
    // 本方法不得为了删除成功而递归移除子项、修改 ACL 或只读属性、跟随最终
    // 链接、删除身份变化后的新对象，或者把目录非空降级成可忽略警告。所有
    // 可报告条件必须结构化返回，不得 panic。
    //
    // # 取消、重试与持久性
    //
    // 从未轮询的 Future 不得打开目录、登记许可或提交删除。原生删除尚未
