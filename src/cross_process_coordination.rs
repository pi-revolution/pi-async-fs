// 本地文件跨进程协调的不透明授权令牌。
//
// 本模块只承载原授权值及其适配；根策略纯值属于coordination_root，
// 唯一配置职责属于coordination_root_config。授权/协议的原行为不因分离而改变。
// 原本地适配器仍负责身份/协议核验；远端不会自动继承本地协调能力。
//
// CrossProcessFileAuthority绑定稳定文件身份和目标实例代次，不是OS权限，
// 也不能强制不合作进程遵守协议。详细原合同随下方授权类型保留。

use core::fmt;
use std::sync::Arc;

// 绑定到单个稳定本地文件身份的跨进程协调授权令牌。
//
// # 作用与使用位置
//
// 本类型是标准本地 adapter 建立协调式文件资源时使用的不透明 capability。
// 它把稳定文件身份、目标实例代次（target incarnation）、后端实例、协调
// 协议版本、协调目录的持久代次、全局根目录的稳定身份和内部协调核心绑定
// 在一起。后续独立打开的文件资源可以借用同一个公开授权，并在内部共享其
// 拥有型核心；读取、追加、刷新和映射方法无需重复接收本令牌。
//
// 它不是文件内容 buffer、操作系统访问权限、长期独占文件锁或能够强制不
// 合作进程服从的安全凭据。令牌也不证明路径始终指向原文件；每次建立资源
// 或执行命名空间变更仍必须同时核验稳定身份、目标实例代次和协议状态，防止
// 删除重建、替换、硬链接或路径别名使授权静默转移到另一对象。
//
// 目标实例代次只在显式协调式删除已经把旧实例发布为 `Removed`，并由显式
// 协调式创建协议建立新目标时更换。最后一个授权或资源的 `Drop`、普通打开、
// 进程重启和暂时没有参与者都不得自动轮换它。旧实例对应的授权可以安全
// `Drop`，但后续打开、映射和命名空间变更必须明确拒绝该授权。
//
// # 安全边界
//
// 建立本令牌的后续公共入口必须是 `unsafe`：调用方需要承诺所有可能破坏
// 文件稳定性或操作矩阵的相关进程、句柄和映射都遵守相同协调协议，并选择
// 相同物理协调根目录。不合作进程、库外文件句柄、另一份未共享全局状态的
// 库实例和未经验证的网络或用户态文件系统不受本令牌自动控制。
//
// 该 `unsafe` 建立点允许后续绑定了授权的协调式映射方法采用安全 Rust
// interface；它没有消除 `memmap2` 对外部文件稳定性的实际要求，只是把无法
// 由操作系统完全证明的责任集中到一个明确入口。
//
// # 生命周期、线程与清理
//
// 公开令牌刻意不实现 `Clone`、`Copy` 或 `Default`。调用方可以通过共享引用
// 并发独立打开多个资源；内部 adapter 可以零成本共享私有引用计数核心，但
// 不向调用方暴露该实现。令牌先行 `Drop` 不得使已经打开的资源、映射或在途
// 操作失效，因为它们各自拥有必要内部状态。
//
// 公开授权值本身不算活动文件资源，也不持有阻止协调式删除的跨进程共享
// 生命周期租约。否则借用授权执行删除会被自身阻塞，多个独立建立的授权也会
// 让目标无法在授权仍可安全 `Drop` 时退役。授权只能提供建立新受管资源所需
// 的身份和协议依据；每次资源建立仍须重新经过状态、实例代次和身份核验。
//
// 授权也不永久持有目标文件的原生句柄。它拥有的是不可变的稳定身份值、受管
// 定位信息、协调目录代次、目标实例代次和 sidecar 协调状态，而不是隐藏的
// 文件占用。建立授权时用于验证身份的临时目标句柄必须在返回前关闭；协调式
// 创建同时返回的首个文件资源持有自己的独立句柄，不能把授权验证句柄同时
// 当成授权字段和文件资源。只有实际文件资源、映射和在途完成所有者持有其
// 生命周期所需的目标句柄。
//
// 后续打开或命名空间操作必须先加入正确的生命周期锁域，再重新打开目标，
// 并把新句柄取得的稳定身份与授权及当前 `Published` 记录同时核对。由此，
// 仅有旧授权存活不会在 Windows 上把删除长期维持为待处理状态，也不会阻止
// 同一定位符在旧实例完整退役后由显式协调协议建立新的目标实例。
//
// 标准本地 adapter 必须在私有协调核心中按“当前进程 + 稳定文件身份 + 目标
// 实例代次”聚合活动所有者。第一个文件资源、映射、候选获取或取消后的在途
// 完成所有者进入时取得一把跨进程共享生命周期租约，最后一个退出时释放；
// 同进程后续所有者只增加私有计数，不为每个公开对象重复打开锁文件。只读
// 映射的零成本克隆通过共享私有所有者继续维持同一租约。
//
// 协调式删除必须先关闭当前进程的新资源准入并证明私有活动计数为零，再非
// 阻塞地尝试取得同一锁域的排它生命周期租约。取得失败立即报告冲突，不能
// 等待其它进程释放资源；取得成功才证明所有合作进程当前均无活动资源。
// 生命周期租约不替代追加串行锁、MMAP 范围锁或其它操作级协调。
//
// `Drop` 不执行强刷新、阻塞等待或协调目录删除。协调目录不是普通临时目录，
// 只能由以后单独设计的离线垃圾回收流程在证明无活动参与者后清理。
//
// `Send` 与 `Sync` 由私有字段自动获得，不使用手写 `unsafe impl`。类型拥有
// 全部状态并满足 `'static`；它不实现判等、排序、哈希、序列化、`AsRef`、
// `Borrow`、`Deref` 或公开转换，因为这些能力容易把令牌表示误认为稳定文件
// 身份、跨进程传输格式或底层锁句柄。
/// 绑定到单个文件目标实例的跨进程协调授权。
///
/// 本类型不透明、不可克隆，也不是操作系统权限、文件内容缓冲区或可序列化的
/// 跨进程凭据。它只适用于建立时核验的 namespace、目标实例与协调配置；
/// 删除后同名重建的文件不得复用旧授权。授权可在线程间移动和共享借用，且
/// 可以先于由它打开的文件资源释放，不会使既有资源失效。
///
/// 该值本身不算活动文件资源，也不会单独阻止协调式删除。其安全保证依赖
/// 建立授权的 `unsafe` 前提持续成立：所有相关进程均合作，协调位置可信，
/// 并且同一物理目标在所有合作进程中始终使用相同的物理父目录和原生末级
/// 文件名。不同硬链接名不能作为同一协调目标交替使用。
pub struct CrossProcessFileAuthority {
    pub(crate) core: Arc<crate::local::CrossProcessAuthorityCore>,
}

impl CrossProcessFileAuthority {
    pub(crate) fn from_local_core(
        core: Arc<crate::local::CrossProcessAuthorityCore>,
    ) -> Self {
        Self { core }
    }

    pub(crate) fn local_core(
        &self,
    ) -> &Arc<crate::local::CrossProcessAuthorityCore> {
        &self.core
    }
}

impl fmt::Debug for CrossProcessFileAuthority {
    // 显示脱敏后的后端、协议版本和诊断编号，不泄漏底层锁句柄。
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("CrossProcessFileAuthority")
            .field("backend", &"local")
            .field("protocol_version", &self.core.protocol_version())
            .field("diagnostic_id", &self.core.diagnostic_id())
            .finish_non_exhaustive()
    }
}

impl fmt::Display for CrossProcessFileAuthority {
    // 显示供人阅读的不透明授权摘要，不作为文件身份或序列化格式。
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "local cross-process file authority #{} (protocol v{})",
            self.core.diagnostic_id(),
            self.core.protocol_version(),
        )
    }
}
