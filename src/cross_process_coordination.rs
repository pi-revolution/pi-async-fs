// 本地文件跨进程协调的全局放置策略与授权令牌。
//
// 本模块只声明跨进程协调的公共 interface，不实现文件锁、范围租约、
// 稳定文件身份核验或协调目录管理。第一批次中的函数和 trait 方法均使用
// `todo!()` 占位；调用这些占位接口会 panic。
//
// 跨进程协调使用目标文件以外的专属协调目录保存锁文件、协议版本和范围
// 租约记录。默认策略把协调目录放在目标文件的父目录；应用也可以在首次
// 使用前安装一个进程级自定义根目录。策略一旦由显式设置或首次协调操作
// 冻结，就不能在进程存续期间切换，否则旧资源和新资源可能进入彼此不可见
// 的两个锁域。
//
// [`CrossProcessFileAuthority`] 是绑定到单个稳定文件身份及其目标实例代次
// （target incarnation）的不透明授权令牌。目标实例代次区分同一定位符上
// 先后存在的不同文件生命周期，避免旧授权在删除、重建后静默转移到新文件。
// 它不是操作系统安全权限，也不是可以跨进程序列化的锁句柄；它只证明
// adapter 已经按照冻结的全局策略建立了本库的合作式协调环境。绕过本库
// 的进程、文件句柄或映射仍不受该令牌强制控制。

