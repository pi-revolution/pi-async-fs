// 一次全文件原地覆盖普通错误完成时，对目标内容状态的可证明事实。
//
// # 作用与使用位置
//
// 本类型将进入以后单独冻结的覆盖错误恢复载体，并最终由
// `FileIo` 的全文件覆盖方法在普通错误结果中返回。它描述的是 adapter
// 在错误完成点能够证明的目标文件逻辑内容和长度，不是对后端内部步骤
// 的枚举，也不是一个持续更新的实时文件快照。
//
// 证据的时间边界是本次操作仍持有对应稳定文件身份租约时的普通错误
// 完成点。租约释放后，另一个进程、绕过本库的句柄或后续受管操作仍可以
// 再次改变文件；因此调用方不能把本值当成永久锁定的当前状态。
//
// # 与传输进度的关系
//
// [`crate::TransferProgress`] 表达输入连续前缀在本次覆盖流程中的处理进度；
// 本类型表达目标文件状态证据。二者不能互相推导。例如，先缩短目标
// 再写入的 adapter 可能同时报告 `TransferProgress::Exact { bytes: 0 }`
// 和 [`Self::ExactInputPrefix`] 的零字节前缀：没有处理任何输入字节，但目标
// 已经被明确变为空文件。
//
// 本值不证明普通写管道已排空、文件已执行强刷新、目录项已持久化，
// 或远端对象已达到强一致完成点。这些保证必须由成功合同或显式强刷新
// 接口单独提供。
//
// # 重试边界
//
// 本类型不提供 `is_retry_safe` 之类的便利判断。是否可以重试还取决于错误
// 原因、调用方要求的幂等级别、协调范围和错误完成后是否存在外部修改。
// 只有 [`Self::Unchanged`] 能单独证明本次调用没有改变目标内容；调用方仍须
// 确认具体错误允许重试。
//
// # 基本能力与演进
//
// 本类型刻意不实现 `Clone`、`Copy` 或 `Default`。它实现调试、显示、判等、
// 全序与哈希，以支持诊断和确定性索引；排序只比较证据标签及字段，不表示
// 证据强度、操作先后或恢复优先级。`Send` 与 `Sync` 由字段自动获得，不使用
// 手写 `unsafe impl`。
//
// 本类型不承诺稳定 ABI、整数判别值、序列化格式或可反向解析的文本协议。
// `#[non_exhaustive]` 强制库外调用方保留一个保守匹配分支；后续可以添加更精确
// 的可移植证据，但不能改弱现有变体的语义。
#[non_exhaustive]
/// 全文件覆盖失败时，对目标内容状态的可证明事实。
///
/// 证据只描述本次操作普通错误完成点的目标状态，不是后续实时快照，也不
/// 提供持久化保证。调用方应与传输进度和错误原因共同决定恢复策略。
pub enum OverwriteTargetEvidence {
    // 能证明本次覆盖没有改变目标文件的逻辑内容和长度。
    //
    // 这个结论以本次操作获得排他租约后、任何目标修改之前的状态为
    // 参照。它不承诺文件时间、后端统计、临时上传对象、锁或其它非内容
    // 副作用也一定没有变化。
    /// 能证明本次覆盖没有改变目标的逻辑内容和长度。
    Unchanged,

    // 能证明目标的全部逻辑内容精确等于原始输入的连续前缀。
    /// 能证明目标全部逻辑内容精确等于原始输入的连续前缀。
    ExactInputPrefix {
        // 目标文件的精确逻辑长度，也是从原始输入起点计算的前缀字节数。
        //
        // 本值必须不大于本次原始输入视图的长度。`bytes == 0` 表示目标
        // 已被精确证明为空文件；`bytes == input.len()` 表示所需逻辑内容
        // 已经全部形成，但普通错误仍可来自后续完成步骤，且不证明持久性。
        /// 目标精确逻辑长度，也是原始输入前缀的字节数。
        bytes: usize,
    },

    // 能证明至少一个修改目标内容或长度的步骤已经发生，但无法证明精确结果。
    //
    // 目标可能为空、只包含新前缀、已形成完整新内容，或处于后端可能产生的
    // 其它状态。即使字节恰好与原内容相同，只要已经跨过修改步骤且精确结果
    // 不可证明，adapter 也应使用本变体，而不是 [`Self::Unchanged`]。
    /// 能证明目标修改已经开始，但无法证明精确内容和长度。
    MutationStarted,

    // 无法证明目标是否被改变，也无法给出与原始输入的精确关系。
    //
    // 常见来源包括取消与后台完成竞态、系统调用结果不确定，以及远端提交
    // 响应丢失。调用方不得把本变体当作“零字节已处理”或“目标未变”。
    /// 无法证明目标是否改变或与原始输入的精确关系。
    Unknown,
}

