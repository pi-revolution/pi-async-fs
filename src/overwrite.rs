// 全文件原地覆盖普通错误的诊断、恢复资产和副作用证据载体。
//
// # 作用与使用位置
//
// 以后单独冻结的全文件覆盖方法会按值接收写入 buffer。成功时消费
// 输入；Future 正常轮询到错误完成时，本类型会把以下四项不可分割的信息
// 一次性交还调用方：
//
// 1. 统一的 [`pi_result::Error`] 诊断报告；
// 2. 调用时传入的同一个原始 `B`；
// 3. 输入连续前缀的 [`TransferProgress`]；
// 4. 目标文件的 [`OverwriteTargetEvidence`]。
//
// 现有 [`crate::BufferFailure`] 只表达写入源的错误、恢复和进度，适合严格尾部
// 追加。覆盖可能在没有处理任何输入字节时已经清空目标，因此需要本专用
// 载体；它不给 `BufferFailure` 添加只对覆盖有意义的可选字段，也不通过
// 嵌套载体迫使调用方穿过两层接口才能完成恢复。
//
// # 原始 buffer 的身份
//
// `B` 在类型定义处不带任何约束，因此本载体可以保存 owned buffer、共享
// 所有权 buffer，或具有调用期生命周期的引用值。“同一个原始 `B`”不只意味着
// 字节相等；adapter 还必须按写入 buffer 合同恢复 allocation、容量、引用身份、
// `Cow` 变体、映射 guard、池租约和该类型承诺保持的其它状态。返还原值不会
// 回滚已有文件副作用。
//
// # 成功、普通错误与取消
//
// - 成功路径不产生本值，也不返还 `B`；
// - Future 正常完成为错误时，adapter 必须先停止对脱离载体的访问，再恢复
//   原始 `B`、进度与目标证据；
// - 调用方直接丢弃 Future 时没有返回本值的同步通道。取消后的内存存活、
//   后台完成、租约保持和最终释放必须由覆盖操作 Future 的合同单独规定。
//
// # 重试与交叉不变量
//
// `progress` 和 `target_evidence` 必须同时真实，但不必具有相同的字节数。
// 例如，目标已清空可以与零输入进度同时成立；后端也可能已处理全部输入，
// 但仍无法证明目标提交结果。任何有字节数的进度或精确前缀证据都不得超过
// 本次原始输入视图的长度。库不会根据本载体自动重试覆盖，调用方也必须
// 同时检查错误可重试性、目标证据和外部协调状态。
//
// # 基本能力与线程语义
//
// 字段对库外保持私有，后续通过逐项冻结的借用访问器和一次性拆解方法
// 提供受控访问。本类型不实现 `Clone`、`Copy`、`Default`、判等、排序或哈希：
// 错误报告的诊断帧不具有适合公共合同的稳定值比较语义，而原始 buffer 也是一次性
// 恢复资产。
//
// `Debug` 和 `Display` 不要求 `B` 实现格式化 trait，也不显示 buffer 内容。
// 本类型不实现 [`std::error::Error`]，因为它不是一个可以随意共享、复制或丢弃恢复
// 资产的普通错误对象。`Send` 与 `Sync` 只由 `B` 及其它字段条件性自动获得，
// 不使用手写 `unsafe impl`，也不强制 `B: 'static`。
/// 全文件覆盖失败时的统一诊断、原始缓冲区、进度和目标证据。
///
/// 普通失败返还与调用时同一逻辑值的 `B`，方便调用方检查和恢复；这不表示
/// 目标未改变或可以盲目重试。释放本类型不会回滚文件或执行额外 I/O。
pub struct OverwriteFailure<B> {
    pub(crate) error: Error,
    pub(crate) buffer: B,
    pub(crate) progress: TransferProgress,
    pub(crate) target_evidence: OverwriteTargetEvidence,
}

