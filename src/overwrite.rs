// 全文件原地覆盖失败时的目标状态证据。
//
// 覆盖写同时涉及“输入 buffer 处理了多少”和“目标文件现在能被证明
// 处于什么状态”两个正交维度。[`crate::TransferProgress`] 只表达前者；
// [`OverwriteTargetEvidence`] 表达后者，以避免调用方把“已取回原 buffer”
// 或“处理了零字节”误解成“目标文件一定没有变”。

